//! Which set of rendered icons the interface uses (icon studio,
//! `tools/icon-studio`). Every rendered icon comes in two sets with the
//! same file names: a dark outline for light interface colours and a
//! light outline for dark ones. Automatic picks by the colour scheme's
//! Panel brightness; Preferences > Display > Colors can force either
//! (Jason, 2026-11-20).
use crate::icons::Icon;
use eframe::egui::{Color32, ColorImage};
use serde::{Deserialize, Serialize};

/// The pixel sizes installed per icon and set: the studio's 16, 20, 24 and
/// 32 px renders, its 2× renders of 20, 24 and 32 (16 at 2× is the 32 px
/// render) and 32 at 4×, so a 32-point toolbox icon at 3× or 4× density
/// (a 4K or 5K display, or a large Interface Scale) is scaled down, never
/// up.
pub const PIXELS: [u32; 8] = [16, 20, 24, 32, 40, 48, 64, 128];

// `RENDERED` (which icons are drawn from studio renders, and their slugs)
// and `FILES` (every embedded picture: set folder, slug, pixels, PNG bytes)
// are generated by build.rs from assets/rendered-icons/icons.txt;
// `installed_files_match_the_table` checks they agree with the folder.
include!(concat!(env!("OUT_DIR"), "/rendered_icons_table.rs"));

/// One rendered icon set.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord)]
pub enum IconSet {
    /// For light interface colours.
    DarkOutline,
    /// For dark interface colours.
    LightOutline,
}

impl IconSet {
    /// The set's folder under each icon's own (the renderer writes these).
    pub fn folder(self) -> &'static str {
        match self {
            Self::DarkOutline => "dark-outline",
            Self::LightOutline => "light-outline",
        }
    }

    pub fn label(self) -> &'static str {
        match self {
            Self::DarkOutline => "Dark Outline",
            Self::LightOutline => "Light Outline",
        }
    }
}

/// The Rendered Icon Outline preference.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
pub enum OutlineChoice {
    /// By the colour scheme's Panel colour.
    #[default]
    Automatic,
    Dark,
    Light,
}

impl OutlineChoice {
    pub const ALL: [Self; 3] = [Self::Automatic, Self::Dark, Self::Light];

    /// The set this choice gives with Panel colour `panel`.
    pub fn set(self, panel: Color32) -> IconSet {
        match self {
            Self::Automatic if is_light(panel) => IconSet::DarkOutline,
            Self::Automatic => IconSet::LightOutline,
            Self::Dark => IconSet::DarkOutline,
            Self::Light => IconSet::LightOutline,
        }
    }

    /// Dropdown labels; Automatic names the set it gives now.
    pub fn label(self, panel: Color32) -> String {
        match self {
            Self::Automatic => format!("Automatic ({})", self.set(panel).label()),
            Self::Dark => IconSet::DarkOutline.label().into(),
            Self::Light => IconSet::LightOutline.label().into(),
        }
    }
}

/// WCAG relative luminance of an sRGB colour, 0 (black) to 1 (white).
fn luminance(c: Color32) -> f64 {
    let lin = |v: u8| {
        let v = f64::from(v) / 255.;
        if v <= 0.04045 {
            v / 12.92
        } else {
            ((v + 0.055) / 1.055).powf(2.4)
        }
    };
    0.2126 * lin(c.r()) + 0.7152 * lin(c.g()) + 0.0722 * lin(c.b())
}

/// Whether a background is light: brighter than mid grey (#777), where a
/// dark outline starts to contrast better than a light one. Provisional.
pub fn is_light(background: Color32) -> bool {
    luminance(background) > luminance(Color32::from_gray(0x77))
}

thread_local! {
    static CHOICE: std::cell::Cell<OutlineChoice> = const { std::cell::Cell::new(OutlineChoice::Automatic) };
}

/// Follow the Rendered Icon Outline preference (at launch and on change).
pub fn set_choice(choice: OutlineChoice) {
    CHOICE.with(|c| c.set(choice));
}

/// The set rendered icons are drawn from now: the preference, with
/// Automatic judged by the current Panel colour.
pub fn current_set() -> IconSet {
    CHOICE.with(std::cell::Cell::get).set(crate::theme::panel())
}

/// `icon`'s render slug, if it is drawn from renders.
pub fn slug(icon: Icon) -> Option<&'static str> {
    RENDERED.iter().find(|(i, _)| *i == icon).map(|(_, s)| *s)
}

/// The installed size to draw `pixels` from: the smallest at least that
/// big (shrinking a little keeps edges crisp), else the biggest.
pub fn source_pixels(pixels: u32) -> u32 {
    PIXELS
        .into_iter()
        .find(|&p| p >= pixels)
        .unwrap_or(PIXELS[PIXELS.len() - 1])
}

/// `icon` from `set` at `pixels` square, or `None` when it isn't a
/// rendered icon. Exact installed sizes are used as rendered; others are
/// scaled from the next size up.
pub fn rasterize(icon: Icon, set: IconSet, pixels: u32) -> Option<Result<ColorImage, String>> {
    let slug = slug(icon)?;
    let from = source_pixels(pixels);
    let bytes = FILES
        .iter()
        .find(|(s, n, p, _)| *s == set.folder() && *n == slug && *p == from)
        .map(|f| f.3);
    Some((|| {
        let bytes = bytes.ok_or_else(|| format!("Rendered icon {slug} {from} px is missing"))?;
        let image = image::load_from_memory_with_format(bytes, image::ImageFormat::Png)
            .map_err(|e| format!("Rendered icon {slug}: {e}"))?
            .into_rgba8();
        let image = if image.width() == pixels && image.height() == pixels {
            image
        } else {
            image::imageops::resize(
                &image,
                pixels.max(1),
                pixels.max(1),
                image::imageops::FilterType::Triangle,
            )
        };
        Ok(ColorImage::from_rgba_unmultiplied(
            [pixels.max(1) as usize; 2],
            image.as_raw(),
        ))
    })())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::theme::ColorId;
    use crate::theme::presets::Preset;

    #[test]
    fn automatic_follows_the_panel_and_the_others_force_a_set() {
        let dark = Color32::from_rgb(0x30, 0x32, 0x36);
        let light = Color32::from_rgb(0xE6, 0xE8, 0xEA);
        let auto = OutlineChoice::Automatic;
        assert_eq!(auto.set(dark), IconSet::LightOutline);
        assert_eq!(auto.set(light), IconSet::DarkOutline);
        for panel in [dark, light] {
            assert_eq!(OutlineChoice::Dark.set(panel), IconSet::DarkOutline);
            assert_eq!(OutlineChoice::Light.set(panel), IconSet::LightOutline);
        }
        assert_eq!(auto.label(dark), "Automatic (Light Outline)");
        assert_eq!(OutlineChoice::Dark.label(dark), "Dark Outline");
    }

    #[test]
    fn built_in_schemes_get_the_set_their_panel_calls_for() {
        // Every built-in scheme has a dark Panel (Fog too: #3A4048).
        for preset in Preset::ALL {
            let panel = preset
                .colors()
                .find(|(id, _)| *id == ColorId::Panel)
                .map_or(ColorId::Panel.entry().default, |(_, c)| c);
            let want = if is_light(panel) {
                IconSet::DarkOutline
            } else {
                IconSet::LightOutline
            };
            assert_eq!(
                OutlineChoice::Automatic.set(panel),
                want,
                "{}",
                preset.name()
            );
        }
        assert_eq!(
            OutlineChoice::Automatic.set(ColorId::Panel.entry().default),
            IconSet::LightOutline,
            "the default (Steel) is dark"
        );
    }

    #[test]
    fn the_choice_saves_by_name() {
        let json = serde_json::to_string(&OutlineChoice::Light).unwrap();
        assert_eq!(json, "\"Light\"");
        assert_eq!(
            serde_json::from_str::<OutlineChoice>(&json).unwrap(),
            OutlineChoice::Light
        );
        assert_eq!(OutlineChoice::default(), OutlineChoice::Automatic);
    }

    #[test]
    fn mid_grey_is_the_turning_point() {
        assert!(!is_light(Color32::from_gray(0x77)));
        assert!(is_light(Color32::from_gray(0x78)));
        assert!(is_light(Color32::WHITE));
        assert!(!is_light(Color32::BLACK));
    }

    #[test]
    fn rendered_only_icons_are_rendered() {
        for &(icon, slug) in Icon::RENDERED_ONLY {
            assert_eq!(super::slug(icon), Some(slug), "{icon:?} isn't in RENDERED");
            assert_eq!(Icon::from_slug(slug), Some(icon));
            assert_eq!(icon.slug(), slug);
        }
    }

    #[test]
    fn installed_files_match_the_table() {
        let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("assets/rendered-icons");
        let mut on_disk = Vec::new();
        for set in [IconSet::DarkOutline, IconSet::LightOutline] {
            for entry in std::fs::read_dir(root.join(set.folder())).unwrap() {
                on_disk.push(format!(
                    "{}/{}",
                    set.folder(),
                    entry.unwrap().file_name().into_string().unwrap()
                ));
            }
        }
        on_disk.sort();
        let mut want: Vec<String> = Vec::new();
        for (_, slug) in RENDERED {
            for set in ["dark-outline", "light-outline"] {
                for px in PIXELS {
                    want.push(format!("{set}/{slug}-{px}.png"));
                }
            }
        }
        want.sort();
        // Every listed icon is installed; the folder may hold renders not
        // in use yet (render-icons.sh --install copies them all).
        for file in &want {
            assert!(on_disk.contains(file), "{file} is listed but not installed");
        }
        let mut embedded: Vec<String> = FILES
            .iter()
            .map(|(s, n, p, _)| format!("{s}/{n}-{p}.png"))
            .collect();
        embedded.sort();
        assert_eq!(embedded, want, "FILES and RENDERED disagree");
        let slugs: Vec<_> = RENDERED.iter().map(|(_, s)| *s).collect();
        let mut sorted = slugs.clone();
        sorted.sort();
        assert_eq!(slugs, sorted, "RENDERED is sorted by slug");
    }

    #[test]
    fn rendered_icons_draw_at_every_size_from_either_set() {
        for &(icon, _) in RENDERED {
            for set in [IconSet::DarkOutline, IconSet::LightOutline] {
                for pixels in [12, 16, 19, 24, 32, 36, 48, 64, 96] {
                    let image = rasterize(icon, set, pixels).unwrap().unwrap();
                    assert_eq!(image.size, [pixels as usize; 2]);
                    assert!(image.pixels.iter().any(|p| p.a() > 0), "{icon:?}");
                    assert!(image.pixels.iter().any(|p| p.a() == 0), "{icon:?}");
                }
            }
        }
        assert!(rasterize(Icon::Eye, IconSet::DarkOutline, 16).is_none());
    }

    /// Jason, 2026-11-24: the toolbox's shared top row (Transform, Move,
    /// Rotate, Scale) is one matching set. A studio batch once rendered a
    /// UV "Box Transform" scene under the slug "transform" and replaced the
    /// Transform tool's icon everywhere. Planned studio renders of the row
    /// take their own "-tool" names, so a render saved under one of the
    /// row's old slugs (or any other name) fails here instead of slipping
    /// in.
    #[test]
    fn the_shared_transform_row_uses_its_planned_renders() {
        for (icon, planned) in [
            (Icon::Transform, "transform-tool"),
            (Icon::Move, "move-tool"),
            (Icon::Rotate, "rotate-tool"),
            (Icon::Scale, "scale-tool"),
        ] {
            assert_eq!(slug(icon), Some(planned), "{icon:?}");
            for set in [IconSet::DarkOutline, IconSet::LightOutline] {
                assert!(rasterize(icon, set, 32).is_some(), "{icon:?}");
            }
        }
        for (_, slug) in RENDERED {
            assert!(
                !["transform", "move", "rotate", "scale"].contains(slug),
                "{slug} would replace a transform-row icon"
            );
        }
        assert_eq!(slug(Icon::UvBoxTransform), Some("uv-box-transform"));
    }

    #[test]
    fn the_two_sets_differ_by_their_outline() {
        let dark = rasterize(Icon::Cube, IconSet::DarkOutline, 32)
            .unwrap()
            .unwrap();
        let light = rasterize(Icon::Cube, IconSet::LightOutline, 32)
            .unwrap()
            .unwrap();
        let luma = |c: Color32| u32::from(c.r()) + u32::from(c.g()) + u32::from(c.b());
        // The outermost opaque pixel on the middle row is outline.
        let edge = |img: &ColorImage| {
            let row = &img.pixels[16 * 32..17 * 32];
            *row.iter().find(|p| p.a() > 200).unwrap()
        };
        assert!(luma(edge(&dark)) < luma(edge(&light)));
    }

    #[test]
    fn sources_are_the_next_installed_size_up() {
        assert_eq!(source_pixels(16), 16);
        assert_eq!(source_pixels(17), 20);
        assert_eq!(source_pixels(32), 32);
        assert_eq!(source_pixels(33), 40);
        // Big toolbox icons on dense displays come down from 128, not up
        // from 64.
        assert_eq!(source_pixels(65), 128);
        assert_eq!(source_pixels(96), 128);
        assert_eq!(source_pixels(200), 128);
        assert_eq!(source_pixels(1), 16);
    }

    #[test]
    fn the_preference_picks_the_set_drawn() {
        set_choice(OutlineChoice::Dark);
        assert_eq!(current_set(), IconSet::DarkOutline);
        set_choice(OutlineChoice::Light);
        assert_eq!(current_set(), IconSet::LightOutline);
        set_choice(OutlineChoice::Automatic);
        assert_eq!(
            current_set(),
            OutlineChoice::Automatic.set(crate::theme::panel())
        );
    }
}
