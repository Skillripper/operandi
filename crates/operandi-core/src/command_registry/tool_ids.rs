/// The phrase that starts the tool Modo calls `id`, if Operandi has it.
pub fn tool_phrase(id: &str) -> Option<&'static str> {
    TOOL_PHRASES
        .iter()
        .find(|(m, _)| m.eq_ignore_ascii_case(id))
        .map(|(_, p)| *p)
}
